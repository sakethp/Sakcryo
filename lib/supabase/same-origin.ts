export function isSameOriginRequest(request: Request) {
  const fetchSite = request.headers.get("sec-fetch-site");
  if (fetchSite === "cross-site" || fetchSite === "none") return false;

  const origin = request.headers.get("origin");
  if (!origin || origin === "null") return false;
  let parsedOrigin: URL;
  try {
    parsedOrigin = new URL(origin);
  } catch {
    return false;
  }

  const configuredOrigin = process.env.NEXT_PUBLIC_SITE_URL;
  if (configuredOrigin) {
    try {
      if (parsedOrigin.origin === new URL(configuredOrigin).origin) return true;
    } catch {
      return false;
    }
  }

  const host = request.headers.get("x-forwarded-host")?.split(",")[0].trim()
    ?? request.headers.get("host");
  if (host && parsedOrigin.host.toLowerCase() === host.toLowerCase()) return true;

  // Fetch Metadata is generated by browsers and reflects the requesting page's origin.
  return fetchSite === "same-origin";
}
